local COLORED_HATS_LIGHTS_ADDR <const> = 0x80408300
local VANILLA_BANK_04_OFFSET_US <const> = 0x0007EC20
local S_SEGMENT_TABLE_OFFSET_US <const> = 0x8033B400

local function writebytes(address, bytes)
    for i = 1, #bytes do
        memory.writebyte(address + i - 1, bytes[i])
    end
end

local function clamp255(x)
    return math.max(0, math.min(255, x))
end

local function color_to_lights(rgb)
    local r1, g1, b1 = clamp255(rgb[1]), clamp255(rgb[2]), clamp255(rgb[3])
    local r2, g2, b2 = clamp255(rgb[1] // 2), clamp255(rgb[2] // 2), clamp255(rgb[3] // 2)
    return {
        r2, g2, b2, 0x00, r2, g2, b2, 0x00,
        r1, g1, b1, 0x00, r1, g1, b1, 0x00,
        0x28, 0x28, 0x28, 0x00, 0x00, 0x00, 0x00, 0x00,
    }
end

local function write_ghost_color_to_stream(ghost_index, rgb)
    writebytes(COLORED_HATS_LIGHTS_ADDR + ghost_index * 0x20, color_to_lights(rgb))
end

local function enable_colored_hats()
    local original_display_list_pointers = {0x40119A0, 0x4011A90, 0x4011B80, 0x4012030}
    local bank04_location = memory.readdword(S_SEGMENT_TABLE_OFFSET_US + 0x10)
    local bank04_size = 0x100000 - VANILLA_BANK_04_OFFSET_US
    local bank04_offset = bank04_location - VANILLA_BANK_04_OFFSET_US

    for addr = bank04_location, bank04_location + bank04_size, 4 do
        if (memory.readdword(addr) & 0xFFFF0000) == 0x001B0000 then
            local found_ptr = memory.readdword(addr + 0x14)
            local is_original = false
            for _, v in ipairs(original_display_list_pointers) do
                if found_ptr == v then is_original = true; break end
            end
            if is_original then
                memory.writedword(addr + 0x14, 0x80408200)
                memory.writeword(addr, 0x12A)
            end
        end
    end

    local jump_out_addr = (0x90580 + bank04_offset) + 0x8
    writebytes(jump_out_addr, {0xB8, 0, 0, 0, 0, 0, 0, 0})

    for addr = bank04_location, bank04_location + bank04_size, 4 do
        local value = memory.readdword(addr)
        if value == 0x02580640 then
            memory.writedword(addr, 0x02587fff)
        elseif value == 0x06407fff then
            memory.writedword(addr, 0x7fff7fff)
        end
    end
end

local function apply_hacks()
    for addr, hck in pairs(HACKS) do
        writebytes(addr, hck)
    end
    memory.writedword(0x80407FFC, 0)
    for i = 0, 0x70 - 1, 4 do
        memory.writedword(0x80407F90 + i, 0)
    end
    enable_colored_hats()
    hacks_applied = true
end

local function write_hack_ghost_frame(slot, f)
    local addr = 0x80409B00 + slot * 0x20
    memory.writefloat(addr + 0x00, f.x)
    memory.writefloat(addr + 0x04, f.y)
    memory.writefloat(addr + 0x08, f.z)
    memory.writeword(addr + 0x0E, f.animation_index)
    memory.writedword(addr + 0x10, f.pitch)
    memory.writedword(addr + 0x14, f.yaw)
    memory.writedword(addr + 0x18, f.roll)
    memory.writeword(addr + 0x1C, f.animation_timer)
end

local function get_hack_ghost_frame(i)
    if i >= 1 and i <= #hack_frames then
        return hack_frames[i]
    end
    return hack_frames[#hack_frames]
end

local function update_hack_replay()
    memory.writebyte(0x80407FFF, 1)
    -- Write Mario's hat color (ghost index 0)
    write_ghost_color_to_stream(0, {255, 0, 0})

    local address_source = Addresses[Settings.address_source_index]
    local global_timer = memory.readdword(address_source.global_timer)

    for tm = 0, 0x7F do
        local slot = (tm + global_timer) & 0x7F
        local i = global_timer + tm - hack_base_timer + 1
        write_hack_ghost_frame(slot, get_hack_ghost_frame(i))
    end

    -- Write ghost hat color (ghost index 1, default red)
    write_ghost_color_to_stream(1, {255, 0, 0})
    -- Set transparency
    local ptr = memory.readdword(0x80407FF8) + 0x61
    memory.writebyte(ptr, hack_transparent and 1 or 0)
end

local function writebytes32(f, x)
	local b4 = string.char(x % 256)
	x = (x - x % 256) / 256
	local b3 = string.char(x % 256)
	x = (x - x % 256) / 256
	local b2 = string.char(x % 256)
	x = (x - x % 256) / 256
	local b1 = string.char(x % 256)
	x = (x - x % 256) / 256
	f:write(b4, b3, b2, b1)
end

local function writebytes16(f, x)
	local b2 = string.char(x % 256)
	x = (x - x % 256) / 256
	local b1 = string.char(x % 256)
	x = (x - x % 256) / 256
	f:write(b2, b1)
end

---Writes the current ghost data to the disk.
---@return boolean # Whether the operation succeeded.
---@nodiscard
local function flush()
	local file = io.open(Settings.ghost_path, 'wb')

	if not file then
		return false
	end

	-- Recording is less than one frame long, so write nothing.
	if recording_base_frame == nil then
		file:close()
		return true
	end

	writebytes32(file, recording_base_frame)
	writebytes32(file, #frames)

	for _, value in pairs(frames) do
		writebytes32(file, (value.global_timer - recording_base_frame))
		writebytes32(file, value.x)
		writebytes32(file, value.y)
		writebytes32(file, value.z)
		writebytes16(file, value.animation_index)
		writebytes16(file, value.animation_timer)
		writebytes32(file, value.pitch)
		writebytes32(file, value.yaw)
		writebytes32(file, value.roll)
	end

	file:close()

	return true
end

---Appends a frame to the ghost recording if active, and updates hack replay.
function Ghost.update()
	if is_hack_replaying then
		update_hack_replay()
	end

	if not is_recording then
		return
	end

	if frame == 0 then
		print('Recording ghost...')
		frame = frame + 1
	end

	local address_source = Addresses[Settings.address_source_index]
	local mario_obj = memory.readdword(address_source.mario_object_pointer)
	local global_timer = memory.readdword(address_source.global_timer)

	if recording_base_frame == nil then
		recording_base_frame = global_timer
	end

	if last_global_timer == nil or last_global_timer < global_timer then
		last_global_timer = global_timer
		frames[#frames + 1] = {
			global_timer = (global_timer - 1),
			pitch = memory.readword(mario_obj + OBJ_PITCH_OFFSET),
			yaw = memory.readword(mario_obj + OBJ_YAW_OFFSET),
			roll = memory.readword(mario_obj + OBJ_ROLL_OFFSET),
			x = memory.readdword(mario_obj + OBJ_POSITION_OFFSET),
			y = memory.readdword(mario_obj + OBJ_POSITION_OFFSET + 4),
			z = memory.readdword(mario_obj + OBJ_POSITION_OFFSET + 8),
			animation_index = memory.readword(mario_obj + OBJ_ANIMATION_OFFSET),
			animation_timer = memory.readword(mario_obj + OBJ_ANIMATION_TIMER_OFFSET) - 1,
		}
	end
end

---Stops the ghost recording.
---@return boolean # Whether the operation succeeded.
---@nodiscard
function Ghost.stop_recording()
	if not is_recording then
		return true
	end

	local result = flush()

	is_recording = false
	frames = {}
	frame = 0
	recording_base_frame = nil
	last_global_timer = nil

	return result
end

---Starts a ghost recording.
---@return boolean # Whether the operation succeeded.
---@nodiscard
function Ghost.start_recording()
	if is_recording then
		local result = Ghost.stop_recording()
		if not result then
			return false
		end
	end

	is_recording = true

	return true
end

---@return boolean # Whether a ghost is being recorded.
---@nodiscard
function Ghost.recording()
	return is_recording
end

---Loads a ghost file for replay.
---@param path string The path to the ghost file.
---@return boolean # Whether the operation succeeded.
---@nodiscard
function Ghost.load_replay(path)
    local file = io.open(path, 'rb')
    if not file then
        return false
    end

    local data = file:read('*a')
    file:close()

    if #data < 8 then
        return false
    end

    local base_frame = read_u32(data, 1)
    local frame_count = read_u32(data, 5)

    replay_frames = {}
    hack_frames = {}
    hack_base_timer = base_frame
    local offset = 9
    for _ = 1, frame_count do
        if offset + 31 > #data then break end
        local x = u32_to_float(read_u32(data, offset + 4))
        local y = u32_to_float(read_u32(data, offset + 8))
        local z = u32_to_float(read_u32(data, offset + 12))
        replay_frames[#replay_frames + 1] = {
            global_timer = base_frame + read_u32(data, offset),
            x = x,
            y = y,
            z = z,
        }
        hack_frames[#hack_frames + 1] = {
            x = x,
            y = y,
            z = z,
            animation_index = read_u16(data, offset + 16),
            animation_timer = read_u16(data, offset + 18),
            pitch = read_u32(data, offset + 20),
            yaw = read_u32(data, offset + 24),
            roll = read_u32(data, offset + 28),
        }
        offset = offset + 32
    end

    is_replaying = #replay_frames > 0
    if is_replaying and Settings.address_source_index == 1 then
        is_hack_replaying = true
        hack_transparent = false
        apply_hacks()
    end
    return is_replaying
end

---Stops the ghost replay.
function Ghost.stop_replay()
    replay_frames = {}
    is_replaying = false
    hack_frames = {}
    is_hack_replaying = false
    hacks_applied = false
    if memory then
        memory.writebyte(0x80407FFF, 0)
    end
end

---@return boolean # Whether a ghost is being replayed.
---@nodiscard
function Ghost.replaying()
    return is_replaying
end

---Returns the ghost position for the given global timer, or nil if not found.
---@param global_timer integer
---@return {x: number, y: number, z: number}?
function Ghost.get_replay_position(global_timer)
    if not is_replaying then
        return nil
    end
    local lo, hi = 1, #replay_frames
    while lo < hi do
        local mid = (lo + hi) >> 1
        if replay_frames[mid].global_timer < global_timer then
            lo = mid + 1
        else
            hi = mid
        end
    end
    local f = replay_frames[lo]
    if f == nil then return nil end
    return { x = f.x, y = f.y, z = f.z }
end

---Re-applies RAM hacks after a savestate load, if hack replay is active.
function Ghost.on_loadstate()
    if is_hack_replaying then
        apply_hacks()
    end
end
